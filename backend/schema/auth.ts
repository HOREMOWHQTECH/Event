import mongoose from 'mongoose';

import { STAFF_ROLES } from '../constants/enums.ts';

// ─────────────────────────────────────────────────────────────────────────────
// STAFF USER
// ─────────────────────────────────────────────────────────────────────────────

const staffUserSchema = new mongoose.Schema(
  {
    fullName: {
      type: String,
      required: true,
      maxlength: 255,
      trim: true,
    },
    username: {
      type: String,
      required: true,
      maxlength: 64,
      unique: true,
      trim: true,
      lowercase: true,
    },
    email: {
      type: String,
      maxlength: 255,
      unique: true,
      sparse: true, // allow multiple staff without an email
      trim: true,
      lowercase: true,
    },
    passwordHash: {
      type: String,
      required: true,
      maxlength: 255,
      select: false, // never returned by default queries
    },
    role: {
      type: String,
      enum: {
        values: STAFF_ROLES,
        message: 'Role must be one of: staff, admin',
      },
      required: true,
      default: 'staff',
    },
    totpSecret: {
      type: String,
      maxlength: 128,
      select: false, // never returned by default queries
    },
    totpEnabled: {
      type: Boolean,
      required: true,
      default: false,
    },
    isActive: {
      type: Boolean,
      required: true,
      default: true,
    },
    createdAt: { type: Date, default: Date.now },
    updatedAt: { type: Date, default: Date.now },
  },
  { collection: 'staff_users' }
);

staffUserSchema.pre('save', function () {
  this.updatedAt = new Date();
});

// ─────────────────────────────────────────────────────────────────────────────
// SESSION
// ─────────────────────────────────────────────────────────────────────────────

const sessionSchema = new mongoose.Schema(
  {
    _id: {
      type: String, // session token, generated by the caller (128 chars)
      required: true,
    },
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'StaffUser',
      required: true,
    },
    expiresAt: {
      type: Date,
      required: true,
    },
    revoked: {
      type: Boolean,
      required: true,
      default: false,
    },
    createdAt: { type: Date, default: Date.now },
  },
  {
    collection: 'sessions',
    _id: false, // we supply `_id` ourselves as a string
  }
);

// ─────────────────────────────────────────────────────────────────────────────
// AUDIT LOG
// ─────────────────────────────────────────────────────────────────────────────

const auditLogSchema = new mongoose.Schema(
  {
    staffId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'StaffUser',
      default: null,
    },
    action: {
      type: String,
      required: true,
      maxlength: 64,
      trim: true,
    },
    entityType: {
      type: String,
      required: true,
      maxlength: 64,
      trim: true,
    },
    entityId: {
      type: String,
      required: true,
      maxlength: 64,
      trim: true,
    },
    oldState: {
      type: mongoose.Schema.Types.Mixed,
      default: null,
    },
    newState: {
      type: mongoose.Schema.Types.Mixed,
      default: null,
    },
    ipAddress: {
      type: String,
      maxlength: 45,
      trim: true,
    },
    userAgent: {
      type: String,
      trim: true,
    },
    createdAt: { type: Date, default: Date.now },
  },
  { collection: 'audit_log' }
);

// ─────────────────────────────────────────────────────────────────────────────
// INDEXES
// ─────────────────────────────────────────────────────────────────────────────

// Staff users
// username and email already unique via field-level `unique: true`
staffUserSchema.index({ role: 1 });
staffUserSchema.index({ isActive: 1 });
staffUserSchema.index({ createdAt: -1 });

// Sessions
sessionSchema.index({ userId: 1 });
sessionSchema.index({ revoked: 1 });
// TTL index — MongoDB automatically removes expired sessions.
// Runs every ~60s, so treat it as a cleanup helper, not a hard expiry guarantee.
// Only ONE index on expiresAt is needed: the TTL index *is* a normal index.
sessionSchema.index({ expiresAt: 1 }, { expireAfterSeconds: 0 });

// Audit log
auditLogSchema.index({ staffId: 1 });
auditLogSchema.index({ action: 1 });
auditLogSchema.index({ entityType: 1, entityId: 1 });
auditLogSchema.index({ createdAt: -1 });

// ─────────────────────────────────────────────────────────────────────────────
// EXPORTS
// ─────────────────────────────────────────────────────────────────────────────

export const StaffUser = (mongoose.models.StaffUser || mongoose.model('StaffUser', staffUserSchema)) as mongoose.Model<any>;
export const Session = (mongoose.models.Session   || mongoose.model('Session',   sessionSchema)) as mongoose.Model<any>;
export const AuditLog = (mongoose.models.AuditLog  || mongoose.model('AuditLog',  auditLogSchema)) as mongoose.Model<any>;
